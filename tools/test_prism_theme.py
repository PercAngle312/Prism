"""Check GX tiling, buffer bounds and theme colour anchors using the native C code."""
from pathlib import Path
import subprocess, tempfile

repo=Path(__file__).resolve().parent.parent
program=r'''
#include <assert.h>
#include <stdio.h>
#include "prism_theme.h"
static int r(uint16_t p) {return (p >> 11) * 255 / 31;}
static int g(uint16_t p) {return ((p >> 5) & 63) * 255 / 63;}
static int b(uint16_t p) {return (p & 31) * 255 / 31;}
int main(void) {
    struct {uint16_t before[16], pixels[4096], after[16];} guarded = {{0},{0},{0}};
    for (int i=0;i<16;++i) guarded.before[i]=guarded.after[i]=0x5aa5;
    prism_theme_fill(guarded.pixels);
    for (int i=0;i<16;++i) assert(guarded.before[i]==0x5aa5 && guarded.after[i]==0x5aa5);
    assert(guarded.pixels[0]==prism_theme_pixel(0,0));
    assert(guarded.pixels[4]==prism_theme_pixel(0,1));
    assert(guarded.pixels[16]==prism_theme_pixel(4,0));
    assert(guarded.pixels[256]==prism_theme_pixel(0,4));
    assert(guarded.pixels[4095]==prism_theme_pixel(63,63));
    uint16_t purple=prism_theme_pixel(0,0),orange=prism_theme_pixel(17,47),grey=prism_theme_pixel(63,0);
    assert(b(purple)>r(purple) && r(purple)>g(purple));
    assert(r(orange)>g(orange) && g(orange)>b(orange));
    assert(b(grey)-r(grey)<20 && r(grey)>70);
    puts("P3\n64 64\n255");
    for (int y=0;y<64;++y) for(int x=0;x<64;++x) {
        uint16_t p=prism_theme_pixel(x,y);printf("%d %d %d\n",r(p),g(p),b(p));
    }
    return 0;
}
'''
with tempfile.TemporaryDirectory() as temporary:
    root=Path(temporary);source=root/'theme.c';source.write_text(program)
    binary=root/'theme'
    subprocess.run(['cc','-std=c11','-Wall','-Wextra','-Werror','-pedantic','-fsanitize=undefined','-I',str(repo/'cube/swiss/source/gui'),str(source),'-o',str(binary)],check=True)
    result=subprocess.run([str(binary)],check=True,capture_output=True)
    from prism_theme import theme_rgb565
    native=list(map(int,result.stdout.split()[4:]))
    desktop=[]
    for y in range(64):
        for x in range(64):
            p=theme_rgb565(x,y)
            desktop.extend(((p>>11)*255//31,((p>>5)&63)*255//63,(p&31)*255//31))
    assert native==desktop, 'Desktop/native palette drift'
    # Optional desktop renderer input, generated by the exact native pixel function.
    if len(__import__('sys').argv)>1: Path(__import__('sys').argv[1]).write_bytes(result.stdout)
print('Native GameCube colour flow: GX tile boundaries, buffer guards and purple/orange/grey anchors passed')
